(function() {
  const supportedLangs = ['en', 'es', 'ru'];
  const defaultLang = 'en';

  function getLang() {
    return localStorage.getItem('heed-lang') || defaultLang;
  }

  function setLang(lang) {
    if (!supportedLangs.includes(lang)) return;
    localStorage.setItem('heed-lang', lang);
    applyTranslations(lang);
    updateLangUI(lang);
    document.documentElement.lang = lang;
  }

  function applyTranslations(lang) {
    if (lang === 'en') {
      document.querySelectorAll('[data-i18n-orig]').forEach(el => {
        el.innerHTML = el.getAttribute('data-i18n-orig');
      });
      return;
    }
    const t = translations[lang];
    if (!t) return;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key] !== undefined) {
        if (!el.getAttribute('data-i18n-orig')) {
          el.setAttribute('data-i18n-orig', el.innerHTML);
        }
        el.innerHTML = t[key];
      }
    });
  }

  function updateLangUI(lang) {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });
  }

  function init() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => setLang(btn.dataset.lang));
    });
    const saved = getLang();
    if (saved !== 'en') setLang(saved);
    else updateLangUI('en');
  }

  // Fire immediately if DOM is already parsed (script at bottom of body),
  // otherwise wait for DOMContentLoaded
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
